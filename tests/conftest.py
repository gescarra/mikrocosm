"""
Shared fixtures for the unit suite.

Everything here is HERMETIC: no network, no real keystore, no writes anywhere
except a pytest tmp_path. Two mechanisms make that possible, and both are
production features rather than test scaffolding:

  --keys / --out    render a throwaway fleet into a temp directory
  --use-pin         replay the two build-time URL fetches from a file

The pin is the interesting one. `generate.py` fetches the management SSH keys
and the mgmt_prefixes endpoint while rendering, and a missing SSH key endpoint
is a HARD failure by design. Rendering with zero keys would clear the admin
user's access and put nothing back. That makes the real generator unrunnable on
a machine with no route to those URLs, which includes most CI runners and every
laptop on a plane. Writing a pin by hand sidesteps it without stubbing anything:
the code path under test is the same one production uses to make a pipeline
reproducible.
"""

import hashlib
import json
import pathlib
import subprocess
import sys

import pytest
import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent

# A syntactically real ed25519 public key that isn't anybody's. It only has to
# survive `fetch_lines`-shaped handling and land in the rendered config.
FAKE_SSH_KEY = ("ssh-ed25519 "
                "AAAAC3NzaC1lZDI1NTE5AAAAIAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"
                " ci@test")


@pytest.fixture(scope="session")
def repo_root():
    return ROOT


@pytest.fixture(scope="session")
def topology_text():
    return (ROOT / "topology.yml").read_text()


# A real ed25519 public key that's nobody's, for the automation block. The
# committed topology.yml ships a placeholder on purpose (the private half must
# be generated by whoever will hold it, which is never the test suite) so
# every render in this suite substitutes this one first.
FAKE_CI_KEY = ("ssh-ed25519 "
               "AAAAC3NzaC1lZDI1NTE5AAAAIBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"
               " gitlab-runner@test")


def renderable(topo):
    """Swap the committed automation placeholder for a usable public key.

    topology.yml ships `REPLACE-ME` on purpose: the private half has to be
    generated by whoever will hold it, and that's never a test suite. Every
    render here therefore substitutes a real-but-nobody's key first, in ONE
    place: two tests previously built their own topology file from the raw
    text and started failing on the placeholder instead of on the thing they
    were actually asserting.
    """
    auto = topo.get("automation")
    if isinstance(auto, dict) and any(
            str(k).startswith("REPLACE-ME") for k in (auto.get("keys") or [])):
        auto["keys"] = [FAKE_CI_KEY]
    return topo


@pytest.fixture(scope="session")
def renderable_topology_text(topology_text):
    """The committed topology, as YAML text, in a state that renders."""
    return yaml.safe_dump(renderable(yaml.safe_load(topology_text)),
                          sort_keys=False)


@pytest.fixture
def topology(topology_text):
    """A fresh mutable copy of the real topology, per test.

    The real one on purpose: a validator tested only against toy fixtures
    passes forever while the fleet it actually guards drifts out from under it.
    Tests that want a broken topology start from this and break one thing.
    """
    return renderable(yaml.safe_load(topology_text))


def _write_pin(path, topo_text, ssh_keys=None, mgmt=None):
    path.write_text(json.dumps({
        "topology_sha256": hashlib.sha256(topo_text.encode()).hexdigest(),
        "ssh_keys": [FAKE_SSH_KEY] if ssh_keys is None else ssh_keys,
        "mgmt_prefixes_fetched": mgmt or [],
    }, indent=2, sort_keys=True) + "\n")


class Render:
    """The result of one `generate.py` invocation."""

    def __init__(self, proc, outdir, topo_path, keys_path):
        self.proc = proc
        self.rc = proc.returncode
        self.stdout = proc.stdout
        self.stderr = proc.stderr
        self.out = outdir
        self.topology_path = topo_path
        self.keys_path = keys_path

    @property
    def ok(self):
        return self.rc == 0

    @property
    def output(self):
        """Both streams. Which one a message lands on isn't what a test about
        validation behaviour should be asserting."""
        return self.stdout + self.stderr

    def config(self, fqdn):
        return (self.out / f"{fqdn}.rsc").read_text()

    def configs(self):
        return {p.stem: p.read_text() for p in sorted(self.out.glob("*.rsc"))}

    def manifest(self):
        return json.loads((self.out / "manifest.json").read_text())

    def inventory(self):
        return yaml.safe_load((self.out / "inventory.yml").read_text())

    def pipeline(self):
        return yaml.safe_load((self.out / "pipeline.yml").read_text())


@pytest.fixture
def render(tmp_path, topology_text):
    """Render a topology into a temp dir. Returns a Render.

    Call with no argument for the real topology, or pass a mutated dict. Extra
    CLI flags go in `args`; `check=False` lets a test assert on a FAILING build,
    which is most of what the validation tests do.
    """
    counter = [0]

    def _render(topo=None, args=(), keys=None, use_pin=True):
        counter[0] += 1
        n = counter[0]
        work = tmp_path / f"run{n}"
        work.mkdir()

        if topo is None:
            # Not the raw file: see renderable().
            text = yaml.safe_dump(renderable(yaml.safe_load(topology_text)),
                                  sort_keys=False)
        else:
            text = yaml.safe_dump(topo, sort_keys=False)
        topo_path = work / "topology.yml"
        topo_path.write_text(text)

        pin = work / "pin.json"
        _write_pin(pin, text)

        # A keystore path that persists across renders within one test is what
        # lets the determinism and key-idempotence tests exist at all: the
        # second render must reuse the first render's keys, exactly as a second
        # ./build.sh does.
        keys_path = pathlib.Path(keys) if keys else (tmp_path / "keys.json")
        outdir = work / "out"

        # --use-pin is what keeps the suite hermetic. A test that's
        # specifically about RECORDING a pin has to opt out of replaying one.
        # The two flags are mutually exclusive, which is itself the behaviour
        # test_validation asserts.
        replay = ["--use-pin", str(pin)] if use_pin else []
        proc = subprocess.run(
            [sys.executable, str(ROOT / "generate.py"),
             "--topology", str(topo_path),
             "--keys", str(keys_path),
             "--out", str(outdir),
             *replay, *args],
            capture_output=True, text=True, cwd=ROOT,
        )
        return Render(proc, outdir, topo_path, keys_path)

    return _render


@pytest.fixture
def built(render):
    """One successful render of the real topology. The common case."""
    r = render()
    assert r.ok, f"the committed topology.yml must render:\n{r.output}"
    return r
